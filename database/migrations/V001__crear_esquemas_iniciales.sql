CREATE TABLE USR_ACADEMIA.ESTUDIANTES (
    ID_ESTUDIANTE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(100) UNIQUE NOT NULL,
    FECHA_INGRESO DATE DEFAULT SYSDATE
);

CREATE TABLE USR_CLINICA.PACIENTES (
    ID_PACIENTE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE VARCHAR2(100) NOT NULL,
    HISTORIAL_REF VARCHAR2(50) UNIQUE,
    FECHA_NACIMIENTO DATE
);

CREATE TABLE USR_RETAIL.PRODUCTOS (
    ID_PRODUCTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE_PRODUCTO VARCHAR2(150) NOT NULL,
    PRECIO NUMBER(10,2) CHECK (PRECIO >= 0),
    STOCK NUMBER DEFAULT 0
);

CREATE TABLE USR_LOGISTICA.ENVIOS (
    ID_ENVIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DIRECCION_DESTINO VARCHAR2(250) NOT NULL,
    ESTADO VARCHAR2(30) DEFAULT 'PENDIENTE'
);

CREATE TABLE USR_FINTECH.CUENTAS (
    ID_CUENTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITULAR VARCHAR2(100) NOT NULL,
    SALDO NUMBER(15,2) DEFAULT 0.00
);

COMMIT;
